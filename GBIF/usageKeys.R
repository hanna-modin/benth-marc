# Function to query GBIF Backbone Taxonomy
get_usage_keys <- function(taxa) {
  results <- lapply(taxa, function(taxon) {
    res <- tryCatch({
      name_backbone(name = taxon)
    }, error = function(e) {
      NULL
    })
    if (!is.null(res)) {
      data.frame(
        taxon = taxon,
        usageKey = res$usageKey,
        scientificName = res$scientificName,
        rank = res$rank,
        status = res$status,
        matchType = res$matchType,
        stringsAsFactors = FALSE
      )
    } else {
      data.frame(
        taxon = taxon,
        usageKey = NA,
        scientificName = NA,
        rank = NA,
        status = NA,
        matchType = NA,
        stringsAsFactors = FALSE
      )
    }
  })
  do.call(rbind, results)
}
